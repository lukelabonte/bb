import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";
import {
  parseTemplateVariableDeclarations,
  validateTemplateBody,
  validateTemplateMetadata,
  type TemplateVariableDeclaration,
} from "../src/template-validation.ts";
import { writeGeneratedFile } from "./write-generated.mjs";

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const templatesDir = path.join(packageRoot, "src", "templates");
const outputPath = path.join(
  packageRoot,
  "src",
  "generated",
  "templates.generated.ts",
);

interface GeneratedTemplateDefinition {
  body: string;
  editingNotes: string;
  id: string;
  intent: string;
  kind: string;
  summary: string;
  title: string;
  variables: TemplateVariableDeclaration[];
}

function asNonEmptyString(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : undefined;
}

function toTemplateId(fileName: string): string {
  const baseName = fileName.replace(/\.md$/u, "");
  const segments = baseName.split("-");
  return segments
    .map((segment, index) =>
      index === 0
        ? segment
        : `${segment.slice(0, 1).toUpperCase()}${segment.slice(1)}`,
    )
    .join("");
}

function generateTemplateVariablesInterface(
  variableInfos: { id: string; variables: TemplateVariableDeclaration[] }[],
): string {
  const lines = [];
  lines.push("export interface TemplateVariables {");
  for (const { id, variables } of variableInfos) {
    if (variables.length === 0) {
      lines.push(`  ${id}: Record<string, never>;`);
    } else {
      lines.push(`  ${id}: {`);
      for (const { name, optional } of variables) {
        const optionalMark = optional ? "?" : "";
        lines.push(`    ${name}${optionalMark}: string;`);
      }
      lines.push("  };");
    }
  }
  lines.push("}");
  return lines.join("\n");
}

const fileNames = (await readdir(templatesDir))
  .filter((fileName) => fileName.endsWith(".md"))
  .sort();

const definitions: GeneratedTemplateDefinition[] = [];
const allVariableInfo: {
  id: string;
  variables: TemplateVariableDeclaration[];
}[] = [];
const validationErrors: string[] = [];

for (const fileName of fileNames) {
  const raw = await readFile(path.join(templatesDir, fileName), "utf8");
  const parsed = matter(raw);
  const id = toTemplateId(fileName);
  const kind = asNonEmptyString(parsed.data.kind);
  const title = asNonEmptyString(parsed.data.title);
  const summary = asNonEmptyString(parsed.data.summary);
  const intent = asNonEmptyString(parsed.data.intent);
  const editingNotes = asNonEmptyString(parsed.data.editingNotes);
  const body = parsed.content.trim();
  const { declarations, errors: variableErrors } =
    parseTemplateVariableDeclarations(parsed.data.variables);

  const metadataErrors = validateTemplateMetadata(id, {
    editingNotes,
    intent,
    kind,
    summary,
    title,
  });
  const bodyValidation = validateTemplateBody({
    body,
    declaredVariables: declarations,
    templateId: id,
  });
  validationErrors.push(
    ...metadataErrors,
    ...variableErrors.map((error) => `Template "${id}": ${error}`),
    ...bodyValidation.errors,
  );
  for (const warning of bodyValidation.warnings) {
    console.warn(`Warning: ${warning}`);
  }

  definitions.push({
    body,
    editingNotes: editingNotes ?? "",
    id,
    intent: intent ?? "",
    kind: kind ?? "",
    summary: summary ?? "",
    title: title ?? "",
    variables: declarations,
  });
  allVariableInfo.push({ id, variables: declarations });
}

if (validationErrors.length > 0) {
  for (const error of validationErrors) {
    console.error(`Error: ${error}`);
  }
  process.exit(1);
}

const templateVariablesBlock =
  generateTemplateVariablesInterface(allVariableInfo);

const output = `/* oxlint-disable */
// Generated by packages/templates/scripts/generate-templates.ts. Do not edit directly.

export const templateDefinitions = ${JSON.stringify(definitions, null, 2)} as const;

export type TemplateDefinition = (typeof templateDefinitions)[number];

${templateVariablesBlock}

export type TemplateId = keyof TemplateVariables;
`;

await writeGeneratedFile(outputPath, output);
